let currentImages = [];
let currentImageIndex = 0;
let previousActiveElement = null;


/* ========================================
   DISPLAY GALLERY IMAGE
======================================== */

function showGalleryImage(index) {

    currentImageIndex = index;

    const imagePath = currentImages[currentImageIndex];

    modalImage.src = imagePath;
    modalImage.alt = modalTitle.textContent + " – Image " + (index + 1);

    imageCounter.textContent =
        (currentImageIndex + 1) + " / " + currentImages.length;

    const thumbnails =
        modalThumbnails.querySelectorAll(".modal-thumbnail");

    thumbnails.forEach((thumbnail, i) => {
        thumbnail.classList.toggle("active", i === currentImageIndex);
    });

}


/* ========================================
   CREATE IMAGE THUMBNAILS
======================================== */

function createThumbnails() {

    modalThumbnails.innerHTML = "";

    currentImages.forEach((imagePath, index) => {

        const thumbnail = document.createElement("button");

        thumbnail.className = "modal-thumbnail";
        thumbnail.type = "button";
        thumbnail.setAttribute(
            "aria-label",
            "View image " + (index + 1)
        );

        const image = document.createElement("img");

        image.src = imagePath;
        image.alt = "Project thumbnail " + (index + 1);
        image.loading = "lazy";

        thumbnail.appendChild(image);

        thumbnail.addEventListener("click", () => {
            showGalleryImage(index);
        });

        modalThumbnails.appendChild(thumbnail);

    });

    const hasMultipleImages = currentImages.length > 1;

    galleryControls.style.display =
        hasMultipleImages ? "flex" : "none";

    modalThumbnails.style.display =
        hasMultipleImages ? "flex" : "none";

}


/* ========================================
   CREATE PROJECT INFORMATION
======================================== */

function createProjectDetails(project) {

    modalDetails.innerHTML = "";

    // Project information
    const information = [];

    if (project.date) {
        information.push("Date: " + project.date);
    }

    if (project.price) {
        information.push("Price Range: " + project.price);
    }

    if (project.duration) {
        information.push("Duration: " + project.duration);
    }

    if (project.industry) {
        information.push("Industry: " + project.industry);
    }

    if (information.length > 0) {

        const infoBlock = document.createElement("div");
        infoBlock.className = "modal-detail-block";

        const heading = document.createElement("h3");
        heading.textContent = "Project Information";

        const paragraph = document.createElement("p");
        paragraph.textContent = information.join("  •  ");

        infoBlock.appendChild(heading);
        infoBlock.appendChild(paragraph);

        modalDetails.appendChild(infoBlock);

    }

    // Other project details
    project.details.forEach(detail => {

        const detailBlock = document.createElement("div");
        detailBlock.className = "modal-detail-block";

        const heading = document.createElement("h3");
        heading.textContent = detail.heading;

        const paragraph = document.createElement("p");
        paragraph.textContent = detail.text;

        detailBlock.appendChild(heading);
        detailBlock.appendChild(paragraph);

        modalDetails.appendChild(detailBlock);

    });

}


